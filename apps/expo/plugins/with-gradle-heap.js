/**
 * Config plugin — raise the Gradle JVM heap so a RELEASE Android build can finish.
 *
 * WHY THIS IS A PLUGIN AND NOT AN EDIT TO `android/gradle.properties`
 * ------------------------------------------------------------------
 * `apps/expo/android/` is a CNG (Continuous Native Generation) output directory and is GITIGNORED
 * (`.gitignore` → `android/`). Editing `gradle.properties` in place works exactly once, on one
 * machine: the next `expo prebuild` regenerates the file from the React Native template and a fresh
 * clone never had it at all. So a heap value that lives only there is not a fix — it is a local
 * workaround that silently evaporates, and the failure it prevents costs ~11 minutes before it
 * announces itself.
 *
 * Story 20.8 paid that cost: the first-ever release build in this repo died with
 * `OutOfMemoryError: Java heap space` in `:app:mergeExtDexRelease` (R8/D8 dex merging is the peak
 * memory step of a release build, and it is not reached by a debug build — which is why every debug
 * build up to that point was green on the template's default `-Xmx2048m`).
 *
 * `expo-build-properties` — already configured in `app.json` — cannot express this: its Android
 * schema covers compile/target SDK, R8/proguard, packaging options and Maven repos, but has no
 * gradle.properties / jvmargs option (checked against the installed
 * `expo-build-properties/build/pluginConfig.d.ts`). `withGradleProperties` is the supported
 * mechanism for exactly this, so it stays a 30-line local plugin rather than a new dependency.
 *
 * Values: 6144m heap with 1024m metaspace. The heap is what dex merging exhausts; metaspace is
 * raised alongside it because Gradle's own default (512m) is tight once the daemon has loaded the
 * AGP + Kotlin + Sentry plugin classloaders for a release run.
 */

const { withGradleProperties } = require('@expo/config-plugins');

const JVM_ARGS = '-Xmx6144m -XX:MaxMetaspaceSize=1024m';

/** Marker in our own comment — the handle we use to drop the previous run's copy. */
const MARKER = 'apps/expo/plugins/with-gradle-heap.js';

const COMMENT =
  `Raised from the RN template default (-Xmx2048m) by ${MARKER} — ` +
  'a release build OOMs in :app:mergeExtDexRelease below this. Edit the plugin, not this file: ' +
  'this file is gitignored and regenerated by every prebuild.';

/**
 * Replace `org.gradle.jvmargs` if the template already set it, otherwise append it.
 *
 * MUST BE IDEMPOTENT. `expo prebuild` WITHOUT `--clean` feeds the EXISTING `gradle.properties`
 * back in as `modResults`, so this runs over its own previous output. Filtering only the property
 * (and not the comment) made every such prebuild append another copy of the comment — unbounded
 * growth, invisible to a test that calls this once. Both our property and our marked comment are
 * dropped before re-adding, so N runs === 1 run.
 */
function setJvmArgs(properties) {
  const next = properties.filter(
    (item) =>
      !(item.type === 'property' && item.key === 'org.gradle.jvmargs') &&
      !(item.type === 'comment' && typeof item.value === 'string' && item.value.includes(MARKER))
  );
  next.push({ type: 'comment', value: COMMENT });
  next.push({ type: 'property', key: 'org.gradle.jvmargs', value: JVM_ARGS });
  return next;
}

module.exports = function withGradleHeap(config) {
  return withGradleProperties(config, (cfg) => {
    cfg.modResults = setJvmArgs(cfg.modResults);
    return cfg;
  });
};

// Exported for the companion test — the plugin body itself needs an Expo config object to drive.
module.exports.setJvmArgs = setJvmArgs;
module.exports.JVM_ARGS = JVM_ARGS;
