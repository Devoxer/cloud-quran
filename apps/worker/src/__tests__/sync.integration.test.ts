/**
 * THE ADVERSARIAL AUTHORIZATION SUITE — the thing the layer this replaces never had.
 *
 * ⚠️ WHY IT IS AN INTEGRATION TEST AND NOT A UNIT TEST. The previous data layer's ownership rule
 * bound `isOwner` to `auth.id == data.creator`, and `creator` was in neither the schema nor any
 * write — so every create was denied for the life of the project and nobody noticed, because
 * nothing ever executed the rule against two identities. A rule nothing exercises is not a rule.
 * So this boots the REAL worker under `wrangler dev` against a REAL local D1, mints two distinct
 * identities through the `getUserId` seam, and asserts that every cross-user READ *and* every
 * cross-user WRITE is refused. A denial covering only reads is the exact bug this story exists
 * to prevent.
 *
 * ⚠️ STORY 5-5 KEPT THE PROMISE THE 5-4 HEADER MADE. Every isolation, LWW, union-merge and
 * ceiling assertion below is unchanged. What moved is only how an identity is obtained: `identity`
 * now calls `POST /api/auth/sign-in/anonymous` and keeps the SESSION COOKIE, where it used to
 * `POST /api/dev/token` and keep a bearer token. The user ids are therefore generated by Better
 * Auth rather than named by the test, so the literal `'user-alice'` assertions became captured
 * ids — the only other change.
 *
 * ⚠️ `--persist-to` A TEMP DIR, NOT `.wrangler/state/`. The suite seeds rows; running it against
 * the developer's own local database would make the second run see the first run's data and pass
 * for the wrong reason. The temp dir also means `pnpm test` never disturbs a dev session.
 */
import { type ChildProcess, execFile, spawn } from 'node:child_process';
import { mkdtempSync, rmSync } from 'node:fs';
import { createRequire } from 'node:module';
import { createServer } from 'node:net';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { DAILY_WRITE_CEILING, utcDay } from '../middleware/write-guard';

const execFileAsync = promisify(execFile);
const require_ = createRequire(import.meta.url);
const workerRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const wranglerBin = join(dirname(require_.resolve('wrangler/package.json')), 'bin/wrangler.js');

/** A browser origin the worker is configured to allow — the web/desktop builds' stand-in. */
const WEB_ORIGIN = 'http://localhost:8082';

/** The session signing key for this run. Local-only, never leaves this process tree. */
const AUTH_SECRET = 'integration-suite-better-auth-secret-0123456789';

let baseUrl = '';
let child: ChildProcess | undefined;
let persistTo = '';
/** Everything the worker has printed. Scanned for the development OTP line — see `otpFor`. */
let workerOutput = '';

function freePort(): Promise<number> {
  return new Promise((resolve, reject) => {
    const server = createServer();
    server.on('error', reject);
    server.listen(0, '127.0.0.1', () => {
      const address = server.address();
      const port = typeof address === 'object' && address ? address.port : 0;
      server.close(() => resolve(port));
    });
  });
}

async function waitForHealth(url: string, deadlineMs: number): Promise<void> {
  const until = Date.now() + deadlineMs;
  let lastError: unknown;
  while (Date.now() < until) {
    try {
      const res = await fetch(`${url}/health`);
      if (res.ok) return;
    } catch (error) {
      lastError = error;
    }
    await new Promise((r) => setTimeout(r, 250));
  }
  throw new Error(`wrangler dev never became healthy at ${url}: ${String(lastError)}`);
}

beforeAll(async () => {
  persistTo = mkdtempSync(join(tmpdir(), 'cq-d1-'));
  const env = { ...process.env, CI: '1', WRANGLER_SEND_METRICS: 'false' };

  // Real migrations, applied by wrangler — the same command a human runs, against the same
  // generated .sql that is committed. If the migration is wrong, this suite cannot start.
  await execFileAsync(
    process.execPath,
    [wranglerBin, 'd1', 'migrations', 'apply', 'cloud-quran', '--local', '--persist-to', persistTo],
    { cwd: workerRoot, env }
  );

  const port = await freePort();
  baseUrl = `http://127.0.0.1:${port}`;
  child = spawn(
    process.execPath,
    [
      wranglerBin,
      'dev',
      '--local',
      '--persist-to',
      persistTo,
      '--ip',
      '127.0.0.1',
      '--port',
      String(port),
      '--var',
      `BETTER_AUTH_SECRET:${AUTH_SECRET}`,
      // The mailer's development escape hatch: no sending domain exists, so `lib/mail.ts` logs
      // the OTP instead of refusing. Without this the email-otp suite could not read a code.
      '--var',
      'ENVIRONMENT:development',
      // The CORS + trustedOrigins allowlist. Needed by the preflight case at the bottom of this
      // file, and by Better Auth's origin check for any cookie-bearing browser POST.
      '--var',
      `ALLOWED_ORIGINS:${WEB_ORIGIN}`,
    ],
    // ⚠️ PIPED, not ignored. The email-OTP suite reads the code out of the worker's own console
    // output — `lib/mail.ts` logs it in development, because no sending domain exists yet. That
    // is the only way to drive a real sign-in code end to end without inventing a test-only
    // route into the auth server, which is exactly the kind of door this story deleted.
    { cwd: workerRoot, env, stdio: ['ignore', 'pipe', 'pipe'] }
  );
  child.stdout?.on('data', (chunk: Buffer) => {
    workerOutput += chunk.toString();
  });
  child.stderr?.on('data', (chunk: Buffer) => {
    workerOutput += chunk.toString();
  });
  await waitForHealth(baseUrl, 90_000);
});

afterAll(async () => {
  if (child && child.exitCode === null) {
    const exited = new Promise<void>((resolve) => child?.once('exit', () => resolve()));
    child.kill('SIGTERM');
    await Promise.race([exited, new Promise((r) => setTimeout(r, 10_000))]);
    if (child.exitCode === null) child.kill('SIGKILL');
  }
  if (persistTo) rmSync(persistTo, { recursive: true, force: true });
});

/**
 * Seed a row straight into the local database, bypassing the API.
 *
 * ⚠️ This is FIXTURE SQL, not query-layer SQL — the "no raw SQL" boundary is about
 * `src/db/queries.ts` keeping the Postgres escape hatch, and a test that needs to place the write
 * counter at 1,999 has no other way to do it. Driving the ceiling through 2,000 real requests
 * would make the suite unusable, and adding a "lower the ceiling" env var would put a production
 * switch in the worker purely so a test could flip it — the worse of the two.
 */
async function seed(sql: string): Promise<void> {
  await execFileAsync(
    process.execPath,
    [
      wranglerBin,
      'd1',
      'execute',
      'cloud-quran',
      '--local',
      '--persist-to',
      persistTo,
      '--command',
      sql,
    ],
    { cwd: workerRoot, env: { ...process.env, CI: '1', WRANGLER_SEND_METRICS: 'false' } }
  );
}

/**
 * Read one number straight out of the local database.
 *
 * ⚠️ FIXTURE SQL, same carve-out as `seed` above. It exists for the one assertion the HTTP surface
 * structurally cannot make: after a merge the guest USER IS DELETED, so there is no session left
 * to ask "did anything stay behind on them". Rows orphaned on a departed user are invisible to
 * every route and permanent in the table.
 */
async function countRows(sql: string): Promise<number> {
  const { stdout } = await execFileAsync(
    process.execPath,
    [
      wranglerBin,
      'd1',
      'execute',
      'cloud-quran',
      '--local',
      '--persist-to',
      persistTo,
      '--json',
      '--command',
      sql,
    ],
    { cwd: workerRoot, env: { ...process.env, CI: '1', WRANGLER_SEND_METRICS: 'false' } }
  );
  const parsed = JSON.parse(stdout) as { results: Record<string, number>[] }[];
  return Number(Object.values(parsed[0].results[0])[0]);
}

const seedBudget = (userId: string, writes: number) =>
  seed(
    `INSERT OR REPLACE INTO write_budget (user_id, day, writes) VALUES ('${userId}', '${utcDay(Date.now())}', ${writes})`
  );

/**
 * An identity, as the worker now understands one: a session COOKIE plus the user id Better Auth
 * minted for it. `token` keeps its name at the call sites below — every one of them is unchanged
 * from 5-4 — but it now carries a cookie header value rather than a bearer token.
 */
type Identity = { cookie: string; userId: string };

type CallOptions = { method?: string; token?: Identity | string; body?: unknown; origin?: string };

async function call(path: string, { method = 'GET', token, body, origin }: CallOptions = {}) {
  // A raw string is a FORGED credential (the "invalid token" cases below); an Identity is a real
  // session. Both land in the same header, which is the point — the seam must refuse the first.
  const cookie = typeof token === 'string' ? token : token?.cookie;
  const res = await fetch(`${baseUrl}${path}`, {
    method,
    headers: {
      ...(cookie ? { cookie } : {}),
      ...(origin ? { origin } : {}),
      ...(body === undefined ? {} : { 'content-type': 'application/json' }),
    },
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  return { status: res.status, json: (await res.json()) as Record<string, unknown> };
}

/**
 * Mint a real anonymous session — the app's own first-launch call, not a test-only door.
 *
 * ⚠️ Story 5-5: this is the ONE function that moved. Everything below it is identity-agnostic,
 * exactly as the 5-4 header promised. The worker no longer has any route that accepts a user id
 * from a caller, so the id comes back rather than going in.
 */
/**
 * A distinct caller address per identity.
 *
 * ⚠️ NOT A WORKAROUND FOR THE RATE LIMITER — IT IS WHAT THESE TESTS MEAN. Alice and Bob are two
 * different people on two different devices, and `lib/auth.ts` keys the limiter on
 * `cf-connecting-ip` (the un-spoofable header the Cloudflare edge writes; upstream's default
 * `x-forwarded-for` is client-supplied and therefore useless as a key). Without this the whole
 * suite is ONE caller hammering `/sign-in/anonymous`, which upstream limits to 3 per 10s — so
 * the fourth identity 429s and a dozen unrelated tests fail for a reason none of them is about.
 * The ceiling itself is asserted deliberately, from one address, in its own describe below.
 */
let callerSeq = 0;
function nextCallerIp(): string {
  callerSeq += 1;
  return `203.0.113.${callerSeq % 250}`;
}

async function identity(): Promise<Identity> {
  const res = await fetch(`${baseUrl}/api/auth/sign-in/anonymous`, {
    method: 'POST',
    headers: { 'content-type': 'application/json', 'cf-connecting-ip': nextCallerIp() },
    body: '{}',
  });
  const setCookie = res.headers.get('set-cookie');
  if (!setCookie) throw new Error(`no session cookie from anonymous sign-in (${res.status})`);
  const body = (await res.json()) as { user?: { id?: string } };
  const userId = body.user?.id;
  if (!userId) throw new Error(`anonymous sign-in returned no user (${res.status})`);
  return { cookie: setCookie.split(';')[0], userId };
}

