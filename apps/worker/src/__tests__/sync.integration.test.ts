describe('no identity', () => {
  const routes: [string, string, unknown][] = [
    ['GET', '/api/sync/reading-position', undefined],
    ['PUT', '/api/sync/reading-position', position(1, 1)],
    ['GET', '/api/sync/preferences', undefined],
    ['PUT', '/api/sync/preferences', prefs(1, 20)],
    ['GET', '/api/sync/audio-position', undefined],
    ['PUT', '/api/sync/audio-position', audio(1, 1)],
    ['GET', '/api/sync/bookmarks', undefined],
    ['POST', '/api/sync/bookmarks', { id: 'anon', surah: 1, verse: 1, createdAt: 1 }],
    ['DELETE', '/api/sync/bookmarks/anon', undefined],
  ];

  it.each(
    routes
  )('%s %s answers 401, not 500 — anonymous is the app normal state', async (method, path, body) => {
    const { status, json } = await call(path, { method, body });
    expect(status).toBe(401);
    expect(json).toEqual({ ok: false, error: 'unauthorized' });
  });

  it('an INVALID credential is refused exactly like none', async () => {
    // The 5-4 shape of this case was a malformed bearer token; the intent — garbage in the
    // credential position must 401, never 500 — is what survives the move to cookies.
    const { status } = await call('/api/sync/reading-position', {
      token: 'better-auth.session_token=not.a.real.token',
    });
    expect(status).toBe(401);
  });

  it('a TAMPERED session cookie is refused — the signature is checked, not just carried', async () => {
    // Alice's cookie with its signature half replaced. Better Auth's token is
    // `<id>.<hmac>`; corrupting the hmac must not authenticate her.
    const [name, value] = alice.cookie.split('=');
    const [id] = decodeURIComponent(value).split('.');
    const forged = `${name}=${encodeURIComponent(`${id}.AAAAAAAAAAAAAAAAAAAAAAAAAAAA`)}`;
    const { status } = await call('/api/sync/reading-position', { token: forged });
    expect(status).toBe(401);
  });

  it('a story 5-4 DEV BEARER TOKEN is refused, and its issuer is gone', async () => {
    // The issuer, the verifier and the route were deleted rather than disabled, so this is not
    // "the gate is closed" — there is nothing left that could open it.
    const bearer = await fetch(`${baseUrl}/api/sync/reading-position`, {
      headers: { authorization: 'Bearer eyJzdWIiOiJ1c2VyLWFsaWNlIn0.AAAA' },
    });
    expect(bearer.status).toBe(401);
    const issuer = await fetch(`${baseUrl}/api/dev/token`, {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify({ userId: 'user-alice' }),
    });
    expect(issuer.status).toBe(404);
  });

  it('and none of that wrote a row — Alice still sees nothing', async () => {
    const { json } = await call('/api/sync/reading-position', { token: alice });
    expect(json).toEqual({ ok: true, position: null });
  });
});

